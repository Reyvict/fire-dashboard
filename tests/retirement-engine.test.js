const assert=require('assert');
const path=require('path');
const Engine=require(path.join(__dirname,'..','retirement-engine.js'));
const fire=require(path.join(__dirname,'..','data.json'));
const retirement=require(path.join(__dirname,'..','retirement-data.json'));
const opening=Engine.buildOpeningState(retirement,fire,'official_plan');
const dec29=fire.monthly.find(x=>x.month==='Dec/29');
assert(dec29,'Dec/29 official accumulation row must exist');
assert(Math.abs(opening.etf-dec29.etfs)<0.01,'Official ETF opening must reconcile');
assert(Math.abs(opening.totalPension-dec29.pension)<0.01,'Official pension opening must reconcile');
assert(Math.abs(opening.pensionVictor+opening.pensionRosely-opening.totalPension)<0.01,'Pension ownership must reconcile');
const baseline=Engine.simulate(retirement,{opening,endYear:2060});
assert(baseline.rows.length>0,'Baseline simulation must produce rows');
assert(baseline.rows.every(r=>Number.isFinite(r.netWorth)),'Every row must have finite net worth');
const bucket=Engine.simulate(retirement,{opening,policy:'three_bucket',endYear:2060});
assert(bucket.rows.length>0,'Three-bucket simulation must produce rows');
const paths=Engine.generatePaths(retirement,{simulations:100,endYear:2050,seed:12345});
const mc1=Engine.monteCarlo(retirement,{opening,paths,endYear:2050});
const mc2=Engine.monteCarlo(retirement,{opening,paths,endYear:2050});
assert.strictEqual(mc1.successRate,mc2.successRate,'Monte Carlo success must be reproducible');
assert.strictEqual(mc1.medianRealEnd,mc2.medianRealEnd,'Monte Carlo median must be reproducible');
const validation=Engine.validate(retirement,fire);
for(const t of validation.tests)assert(t.ok,'Model validation failed: '+t.name+' '+(t.detail||''));
assert.strictEqual(validation.passed,validation.total,'All model validation checks must pass');
const deltas=Engine.decisionDeltas(retirement,{opening,fire,simulations:80,endYear:2050});
assert.strictEqual(deltas.cases.length,4,'Four decision deltas must be produced');
const stresses=Engine.runStress(retirement,{opening,policy:'three_bucket',endYear:2060});
assert(stresses.length>=4,'Core deterministic stress scenarios must exist');
console.log('retirement-engine: '+validation.passed+'/'+validation.total+' validation checks passed');
